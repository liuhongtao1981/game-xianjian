const assert=require('node:assert/strict');
const {createHarness}=require('./game-harness');
const h=createHarness(),run=code=>h.evaluate(code);
run(`reset();G.state='playing';G.enemies=[];`);
assert.equal(run('P.mana'),100);
run(`tryDash();`);
assert.equal(run('P.mana'),90,'tap costs 10 immortal power');
assert.equal(run('P.invuln'),.32,'tap keeps its short invulnerability');
run(`tryDash();`);assert.equal(run('P.mana'),90,'cooldown cannot double-spend');
run(`P.dash=0;P.mana=100;ImmortalMovement.reset();ImmortalMovement.press();for(let i=0;i<120;i++)ImmortalMovement.update(1/60,true);`);
assert.ok(Math.abs(run('P.mana')-60)<1e-7,'two seconds cost40 at60FPS');
run(`P.mana=100;ImmortalMovement.reset();ImmortalMovement.press();for(let i=0;i<60;i++)ImmortalMovement.update(1/30,true);`);
assert.ok(Math.abs(run('P.mana')-60)<1e-7,'drain independent of framerate');
assert.ok(Math.abs(run('ImmortalMovement.update(.1,true)')-1.7)<1e-9);
run(`ImmortalMovement.release();ImmortalMovement.update(.75,false);`);
assert.ok(Math.abs(run('P.mana')-58)<1e-7,'recovery respects delay');
run(`ImmortalMovement.update(1,false);`);assert.ok(Math.abs(run('P.mana')-74)<1e-7);
run(`P.mana=1;ImmortalMovement.press();ImmortalMovement.update(.1,true);`);
assert.equal(run('P.mana'),0);assert.equal(run('ImmortalMovement.status().exhausted'),true);
run(`ImmortalMovement.restore(50);`);
assert.equal(run('ImmortalMovement.update(.1,true)'),1,'exhaustion does not auto-repeat while held');
run(`ImmortalMovement.release();ImmortalMovement.press();`);
assert.ok(Math.abs(run('ImmortalMovement.update(.1,true)')-1.7)<1e-9);
run(`const beforePause=P.mana;G.state='paused';ImmortalMovement.update(5,true);`);
assert.equal(run('P.mana===beforePause'),true,'paused frames cannot consume power');
run(`clearInput();G.state='playing';`);assert.equal(run('ImmortalMovement.status().held'),false);
run(`ImmortalMovement.press('keyboard');ImmortalMovement.press('pointer:7');ImmortalMovement.release('pointer:7');`);
assert.equal(run('ImmortalMovement.status().held'),true,'lifting touch does not cancel held keyboard');
run(`clearInput();P.cultivation.realm=13;P.mana=9999;ImmortalMovement.ensure();`);
assert.equal(run('P.mana'),204,'realm cap is clamped');
// Exercise movement integration on an unobstructed part of the real world.
run(`reset();G.state='playing';G.enemies=[];keys.d=true;const origin={x:P.x,y:P.y};for(let i=0;i<15;i++)updatePlayer(1/60);const normalDistance=Math.hypot(P.x-origin.x,P.y-origin.y);P.x=origin.x;P.y=origin.y;P.vx=P.vy=0;ImmortalMovement.press();for(let i=0;i<15;i++)updatePlayer(1/60);`);
assert.ok(run('Math.hypot(P.x-origin.x,P.y-origin.y)>normalDistance*1.6'),'holding increases actual movement');
run(`const legacy=JourneyProgress.capture(P);delete legacy.mana;delete legacy.alchemy;`);
assert.equal(run('JourneyProgress.validBuild(legacy)'),true,'old snapshots remain loadable');
assert.equal(run('JourneyProgress.capture(legacy).mana'),100,'old saves gain a full power meter');
run(`clearInput();RunSave.start(0,false,false,false,true);P.mana=37;RunSave.save();`);
const reload=createHarness({storage:h.storage});reload.evaluate('RunSave.continueRun();');
assert.equal(reload.evaluate('P.mana'),37,'reload preserves exact immortal power');
assert.equal(reload.evaluate('ImmortalMovement.status().held'),false,'reload never inherits a held input');
console.log('PASS: tap, held movement, framerate, depletion, recovery, pause, mixed input, realm cap, legacy migration, reload');
