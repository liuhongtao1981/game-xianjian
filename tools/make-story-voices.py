"""Generate one consistent heavy Mandarin narrator for every authored story scene."""
import asyncio
import hashlib
import json
from pathlib import Path
import subprocess
import tempfile
import edge_tts

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = json.loads((ROOT / 'docs/story-voice-cues.json').read_text(encoding='utf-8'))
OUTPUT = ROOT / 'prototype/assets/audio/voice-heavy'

def probe(path):
    result = subprocess.run(['ffprobe', '-v', 'error', '-show_entries', 'format=duration', '-of', 'json', str(path)], check=True, capture_output=True, text=True)
    return float(json.loads(result.stdout)['format']['duration'])

async def main():
    OUTPUT.mkdir(parents=True, exist_ok=True)
    profile = MANIFEST['profile']
    semaphore = asyncio.Semaphore(3)
    async def generate(cue):
        destination = OUTPUT / (cue['id'] + '.mp3')
        metadata = OUTPUT / (cue['id'] + '.json')
        signature = hashlib.sha256(json.dumps([cue, profile], ensure_ascii=False, sort_keys=True).encode()).hexdigest()
        if destination.exists() and metadata.exists():
            saved = json.loads(metadata.read_text(encoding='utf-8'))
            if saved.get('signature') == signature:
                return saved
        async with semaphore:
            with tempfile.TemporaryDirectory(prefix='xunsheng-heavy-') as directory:
                raw = Path(directory) / 'speech.mp3'
                for attempt in range(3):
                    try:
                        speech = edge_tts.Communicate(cue['text'], profile['voice'], rate=profile['rate'], pitch=profile['pitch'])
                        await asyncio.wait_for(speech.save(str(raw)), timeout=65)
                        if probe(raw) < .3:
                            raise RuntimeError('Empty narration')
                        break
                    except Exception:
                        if attempt == 2:
                            raise
                        await asyncio.sleep(2 + attempt * 3)
                filters = 'highpass=f=65,lowpass=f=10000,equalizer=f=170:width_type=o:width=1.2:g=2.2,acompressor=threshold=0.16:ratio=2.1:attack=18:release=150,loudnorm=I=-17:TP=-2:LRA=8,apad=pad_dur=0.15'
                subprocess.run(['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-i', str(raw), '-af', filters, '-ar', '24000', '-ac', '1', '-codec:a', 'libmp3lame', '-b:a', '96k', str(destination)], check=True)
                record = {**cue, **profile, 'engine':'Microsoft Edge neural TTS', 'signature':signature, 'source_sha256':hashlib.sha256(raw.read_bytes()).hexdigest(), 'sha256':hashlib.sha256(destination.read_bytes()).hexdigest(), 'duration':probe(destination), 'file':'assets/audio/voice-heavy/' + destination.name, 'filters':filters}
                metadata.write_text(json.dumps(record, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
                print('Ready: ' + cue['id'] + ' (' + str(round(record['duration'], 2)) + 's)', flush=True)
                return record
    clips = await asyncio.gather(*(generate(cue) for cue in MANIFEST['cues']))
    (OUTPUT / 'manifest.json').write_text(json.dumps({'version':1, 'profile':profile, 'clips':clips}, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    runtime = {'profile':profile, 'clips':{clip['text']:clip['file'] + '?v=' + clip['sha256'][:16] for clip in clips}}
    (ROOT / 'prototype/story-voices.js').write_text('/* One heavy narrator for every story scene; generated by make-story-voices.py. */\nconst StoryVoicePack=' + json.dumps(runtime, ensure_ascii=False, separators=(',', ':')) + ';\n', encoding='utf-8')
    print('Complete: ' + str(len(clips)) + ' heavy narration recordings', flush=True)

if __name__ == '__main__':
    asyncio.run(main())
