// Bake the exact runtime 64-unit navigation graph. Run after changing map geometry.
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {createHarness}=require('./game-harness');
const target=path.resolve(__dirname,'../prototype/navigation-cache.js');
const h=createHarness(),count=h.evaluate('ChapterCatalog.playable'),rows=[];
const check=process.argv.includes('--check'),verify=process.argv.includes('--verify');
for(let stage=0;stage<count;stage++){
 h.evaluate(`Journey.run.stage=${stage};reset();`);
 if(check||verify){
  assert.equal(h.evaluate(`typeof NavigationCache!=='undefined'&&!!NavigationCache.get(${stage},World.navigationKey())`),true,'Navigation cache is stale in chapter '+(stage+1));
  assert.equal(h.evaluate(`NavigationCache.get(${stage},'outdated-geometry')`),null,'Mismatched geometry must use the safe fallback');
  if(verify){const same=h.evaluate(`(()=>{const actual=World.navigationTopology(),cached=NavigationCache.get(${stage},actual.key);return actual.walk.every((value,i)=>value===cached.walk[i])&&actual.neighbors.every((row,i)=>row.length===cached.neighbors[i].length&&row.every((n,j)=>n===cached.neighbors[i][j]));})()`);assert.equal(same,true,'Exact navigation topology differs in chapter '+(stage+1));console.log('Verified chapter '+(stage+1)+' walkable cells and all directed edges');}
  continue;
 }
 const graph=h.evaluate('World.navigationTopology()'),steps=[-graph.cols-1,-graph.cols,-graph.cols+1,-1,1,graph.cols-1,graph.cols,graph.cols+1];
 const cells=Array.from(graph.walk,(walk,i)=>walk?256+graph.neighbors[i].reduce((mask,n)=>mask|(1<<steps.indexOf(n-i)),0):0),runs=[];
 for(const value of cells){if(runs.length&&runs[runs.length-1]===value)runs[runs.length-2]++;else runs.push(1,value);}
 rows.push({key:graph.key,cols:graph.cols,rows:graph.rows,runs});console.log('Baked chapter '+(stage+1)+': '+cells.length+' cells / '+runs.length/2+' runs');
}
if(check||verify){
 assert.equal(h.evaluate(`(()=>{Journey.run.stage=0;reset();const key=World.navigationKey(),first=NavigationCache.get(0,key);if(first!==NavigationCache.get(0,key))return false;for(let stage=1;stage<4;stage++){Journey.run.stage=stage;reset();NavigationCache.get(stage,World.navigationKey());}return NavigationCache.get(0,key)!==first;})()`),true,'Decoded navigation should reuse hot maps and evict maps outside the last three');
 console.log(count+' navigation geometry fingerprints match'+(verify?' with exact topology equivalence':'')+'; cache is bounded to three maps');process.exit(0);
}
const runtime=`/* Generated by node tools/build-navigation-cache.js; exact walkability and eight-neighbor edges. */
const NavigationCache=(()=>{
  const data=${JSON.stringify(rows)};
  const decoded=new Map();
  function get(stage,key){
    const entry=data[stage];if(!entry||entry.key!==key)return null;
    if(decoded.has(stage)){const graph=decoded.get(stage);decoded.delete(stage);decoded.set(stage,graph);return graph;}
    const size=entry.cols*entry.rows,walk=new Uint8Array(size),neighbors=Array.from({length:size},()=>[]),steps=[-entry.cols-1,-entry.cols,-entry.cols+1,-1,1,entry.cols-1,entry.cols,entry.cols+1];
    let cursor=0;
    for(let p=0;p<entry.runs.length;p+=2){const count=entry.runs[p],value=entry.runs[p+1];if(count<1||cursor+count>size)return null;for(let j=0;j<count;j++,cursor++){walk[cursor]=value&256?1:0;for(let bit=0;bit<8;bit++)if(value&(1<<bit))neighbors[cursor].push(cursor+steps[bit]);}}
    if(cursor!==size)return null;
    const graph={walk,neighbors};decoded.set(stage,graph);while(decoded.size>3)decoded.delete(decoded.keys().next().value);return graph;
  }
  return {get};
})();
`;
fs.writeFileSync(target,runtime);console.log('Wrote '+target+' ('+Buffer.byteLength(runtime)+' bytes)');
