const assert=require('node:assert/strict');
const {createHarness}=require('./game-harness');
const h=createHarness();
h.evaluate(`reset();G.state='playing';G.enemies=[];P.spells=Object.fromEntries(Object.keys(SPELLS).map(k=>[k,3]));P.t={};updateSpells(.1);`);
assert.equal(h.evaluate('Motion.status().pendingCasts'),0,'empty field must not queue attack animations');
assert.equal(h.evaluate('P.attack'),0,'idle hero must not begin a casting animation');
assert.equal(h.evaluate('Object.values(P.t).every(t=>t===0)'),true,'ready cooldowns must remain ready while idle');
h.evaluate(`G.enemies=[{id:501,hp:0,x:P.x+30,y:P.y,r:18},{id:502,hp:100,x:P.x+3000,y:P.y,r:18}];updateSpells(.1);`);
assert.equal(h.evaluate('Motion.status().pendingCasts'),0,'dead and distant demons cannot trigger casts');
h.evaluate(`G.enemies=[{id:503,hp:1000,maxHp:1000,x:P.x+90,y:P.y,r:18,type:'imp'}];updateSpells(.1);`);
assert.ok(h.evaluate('Motion.status().pendingCasts')>0,'nearby living demon triggers ready spells immediately');
h.evaluate(`G.enemies=[];updateSpells(.1);`);
assert.equal(h.evaluate('Motion.status().pendingCasts'),0,'last demon disappearing cancels unreleased auto spells');
assert.equal(h.evaluate('P.attack'),0,'last demon disappearing returns hero to movement');
h.evaluate(`Motion.reset();P.spells={gudu:20,jiushen:20};P.t={};G.enemies=[{id:504,hp:1000,x:P.x+1000,y:P.y,r:18}];updateSpells(.1);`);
assert.equal(h.evaluate('Motion.status().pendingCasts'),2,'high-grade spells keep their earned range beyond900');
h.evaluate(`Motion.reset();P.spells={bingxin:3};P.t={};P.shield=P.shieldMax;G.enemies=[{id:505,hp:100,x:P.x+120,y:P.y,r:18}];G.eshots=[];updateSpells(.1);`);
assert.equal(h.evaluate('Motion.status().pendingCasts'),0,'full shield and no projectiles need no protective cast');
h.evaluate(`G.eshots=[{x:P.x+10,y:P.y}];updateSpells(.1);`);
assert.equal(h.evaluate('Motion.status().pendingCasts'),1,'full shield still allows ice to dispel incoming projectiles');
console.log('PASS: idle/dead/distant enemies, immediate reacquisition, cancelled windups, idle cooldowns');
